/** A logger that keeps `acquireSource`'s diagnostics line and nothing else. */
function captureLogger(): {
  logger: Logger;
  lines: Record<string, unknown>[];
} {
  const lines: Record<string, unknown>[] = [];
  const logger: Logger = {
    child: () => logger,
    error: () => undefined,
    warn: () => undefined,
    info: () => undefined,
    debug: (msg, ctx) => {
      if (msg === "summarize acquisition" && ctx !== undefined) lines.push(ctx);
    },
    time: (_msg, fn) => fn(),
  };
  return { logger, lines };
}

const IMRAD_HEADINGS = [
  "Abstract",
  "1. Introduction",
  "2. Methods",
  "3. Results and Discussion",
  "4. Conclusions",
];
const TITLE = "Counting Synthetic Widgets at Three Invented Sites";

describe("P3-T21 IMRaD section detector on getStructuredDocumentText", function () {
  after(async function () {
    setPrefStore(undefined);
    if (created.length > 0) {
      await Zotero.Items.erase(created.map((item) => item.id));
    }
    for (const path of tempFiles) {
      await IOUtils.remove(path, { ignoreAbsent: true });
    }
  });

  it("decodes the pack and narrows the outline and heading blocks (shape measured on 10.0.3)", async function () {
    this.timeout(TEST_TIMEOUT_MS);
    debug(`${LOG} Zotero ${Zotero.version}`);
    const fixtures = [
      ["imrad", makePdf(IMRAD_PAGES)],
      ["imrad-bookmarked", makePdf(IMRAD_PAGES, IMRAD_BOOKMARKS)],
      ["plain", makePdf(PLAIN_PAGES)],
    ] as const;
    for (const [name, bytes] of fixtures) {
      const { attachment } = await importFixture(name, bytes);
      const t0 = Date.now();
      const doc = await getStructuredDocumentText(attachment.id);
      const ms = Date.now() - t0;
      assert.isTrue(isRecord(doc), `${name}: a pack was decoded`);
      describeShape(name, doc, ms);
      const record = doc as Record<string, unknown>;
      assert.strictEqual(
        keysOf(doc),
        "catalog,content,metadata,schemaVersion",
        `${name}: the materialized document's keys`,
      );
      assert.strictEqual(
        String(record.schemaVersion).split(".")[0],
        "1",
        `${name}: schema major version 1`,
      );
      const structure = narrowStructuredDocument(doc);
      debug(`${LOG} ${name}: narrowed ${clip(structure, 2500)}`);
      const flat = (await Zotero.PDFWorker.getFullText(
        attachment.id,
        null,
      )) as { text: string };
      debug(`${LOG} ${name}: getFullText ${clip(flat.text, 1500)}`);
      assert.strictEqual(structure.pageCount, 2, `${name}: two pages`);

      const catalog = record.catalog as Record<string, unknown>;
      const rawOutline = catalog.outline as Record<string, unknown>[];
      if (name === "plain") {
        // The title is the one heading block, and the worker's inferred
        // outline holds it alone.
        assert.deepEqual(
          structure.outline.map((entry) => entry.title),
          ["A Report With No Sections"],
        );
        assert.deepEqual(
          structure.headingBlocks.map((block) => block.text),
          ["A Report With No Sections"],
        );
        continue;
      }
      // Every heading, the title included, is a `heading` block, and the
      // outline anchors each one to its block (`ref: [blockIndex]`).
      assert.deepEqual(
        structure.headingBlocks.map((block) => block.text),
        [TITLE, ...IMRAD_HEADINGS],
        `${name}: heading blocks`,
      );
      assert.deepEqual(
        structure.outline.map((entry) => [entry.blockText, entry.pageIndex]),
        [
          [TITLE, 0],
          ["Abstract", 0],
          ["1. Introduction", 0],
          ["2. Methods", 0],
          ["3. Results and Discussion", 1],
          ["4. Conclusions", 1],
        ],
        `${name}: every outline entry is anchored to its heading block and page`,
      );
      // Native bookmarks carry `source: "native"`; the worker's own inferred
      // entry (the title) carries no `source` at all — and the native entries
      // were anchored to the heading blocks although each `/Dest` points at
      // the top of its page, not at the heading.
      assert.deepEqual(
        rawOutline.map((entry) => entry.source ?? null),
        name === "imrad-bookmarked"
          ? [null, "native", "native", "native", "native", "native"]
          : [null, null, null, null, null, null],
        `${name}: outline sources`,
      );
    }
  });

  it("labels the generated article's sections from the outline, and declares failure on a headingless file", async function () {
    this.timeout(TEST_TIMEOUT_MS);
    setPrefStore(createZoteroPrefStore());
    for (const [name, bytes] of [
      ["imrad-acq", makePdf(IMRAD_PAGES)],
      ["imrad-bookmarked-acq", makePdf(IMRAD_PAGES, IMRAD_BOOKMARKS)],
      ["plain-acq", makePdf(PLAIN_PAGES)],
    ] as const) {
      const { parent, attachment } = await importFixture(name, bytes);
      const { logger, lines } = captureLogger();
      const source = await acquireZoteroSource(parent, {
        estimateTokens: (text) => Math.ceil(text.length / 4),
        tryEuropePmc: false,
        logger,
      });
      const structure = await getDocumentStructure(attachment);
      const lineScanOnly = detectSectionsFromPdf(source.text, null);
      debug(
        `${LOG} ${name}: tier=${source.tier} sectionAware=${String(source.sectionAware)} ` +
          `sections=${clip(
            source.sections.map((s) => ({
              labels: s.labels,
              heading: s.heading,
              start: s.start,
              end: s.end,
            })),
            1500,
          )} warnings=${source.warnings.join(",")}`,
      );
      debug(
        `${LOG} ${name}: diagnostics ${clip(lines[0], 1200)}; outline=${structure?.outline.length ?? "null"}; ` +
          `line scan alone: sectionAware=${String(lineScanOnly.sectionAware)} ` +
          `labels=${lineScanOnly.sections.map((s) => s.labels.join("+")).join(",")}`,
      );
      assert.strictEqual(source.tier, "fulltext_pdf", `${name}: Tier 2`);
      assert.strictEqual(lines.length, 1, `${name}: one diagnostics line`);
      const diagnostics = lines[0] ?? {};
      assert.strictEqual(
        diagnostics.structureSkipped,
        null,
        `${name}: the structure was read`,
      );
      for (const section of source.sections) {
        assert.strictEqual(
          source.text.slice(section.start, section.end),
          section.text,
          `${name}: a section's text is its slice of the acquired text`,
        );
      }
      if (name === "plain-acq") {
        assert.isFalse(source.sectionAware, "headingless: sectionAware false");
        assert.deepEqual(source.sections, [], "headingless: no sections");
        continue;
      }
      assert.isTrue(source.sectionAware, `${name}: sectionAware`);
      assert.deepEqual(
        source.sections.map((s) => [s.labels.join("+"), s.heading]),
        [
          ["other", TITLE],
          ["abstract", "Abstract"],
          ["introduction", "1. Introduction"],
          ["methods", "2. Methods"],
          ["results+discussion", "3. Results and Discussion"],
          ["conclusion", "4. Conclusions"],
        ],
        `${name}: labels and headings`,
      );
      // Built on the outline: all six outline headings were located in the
      // flat text and the line scan added nothing. The Methods paragraph
      // starts in lower case, so the scan alone cannot see "2. Methods" (§4.3's
      // "followed by a capitalized sentence") — the outline does.
      assert.strictEqual(diagnostics.structureLocated, 6, `${name}: located`);
      assert.strictEqual(diagnostics.fallbackAdded, 0, `${name}: no fallback`);
      assert.isFalse(
        lineScanOnly.sections.some((s) => s.imrad === "methods"),
        `${name}: the line scan alone misses the Methods heading`,
      );
    }
  });
});
