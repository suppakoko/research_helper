/**
 * `P3-T21`: `getStructuredDocumentText`'s real shape on Zotero 10.0.3, and
 * `docs/06` §4.3's section detector on top of it.
 *
 * ## Why this spec exists
 *
 * The owner ruled on 2026-10-23 (`plan/00` §6 item 271(c)) that the PDF
 * detector is built on the worker's section outline and heading blocks. The
 * shape was decoded once, on Zotero 10.0.2 against real articles (`P0-T18`);
 * this spec measures it again on the installed 10.0.3, through the plugin's
 * own reader (`getStructuredDocumentText` and `narrowStructuredDocument` in
 * `src/zotero/fulltext.ts`), and prints what it found so that `docs/06`
 * §3.3.5 can record it.
 *
 * ## Fixtures
 *
 * Every PDF is **generated by this file**: a two-page "article" in
 * Helvetica with Helvetica-Bold headings at a larger size and white space
 * above each, once without and once with native bookmarks (`/Outlines`), and
 * a two-page title-and-body file with no headings at all. Nothing is
 * downloaded or committed (the `G-12` corpus is not available yet), so this
 * spec says nothing about accuracy on publisher layouts — that is `P3-T22`'s
 * measurement. The Methods paragraph deliberately starts in lower case, so
 * §4.3's line scan ("followed by … a capitalized sentence") cannot see the
 * "2. Methods" heading and only the outline can: the second spec proves the
 * detector is built on the outline, not on the scan.
 *
 * ## What 2026-10-23's first run measured (recorded in `docs/06` §3.3.5)
 *
 * The plugin sandbox has no `require`, and loading Zotero's bundled reader and
 * `pako` as subscripts works. The decoded document's keys are
 * `catalog, content, metadata, schemaVersion` (schema `1.2.0`, processor
 * `pdf` version 14); `catalog` is `{ outline, pages }`. Each outline entry is
 * `{ title, ref: [blockIndex] }`, flat for these files, with
 * `source: "native"` only on bookmark entries; the title came in as an
 * inferred entry in both files, and the native entries were anchored to the
 * heading blocks although each bookmark points at the top of its page. Every
 * heading is a `type: "heading"` block whose text nodes carry `style.bold` —
 * which nothing reads. A two-page file decodes in 20–67 ms. And unlike
 * `acquireFullText.spec.ts`'s single-size pages, `getFullText` put every
 * block of these files on its own line.
 *
 * Everything created is erased and the temp files removed, from an `after`
 * hook inside the `describe` (see `acquireFullText.spec.ts`, "Leaving Zotero
 * quiet for the next spec").
 */

