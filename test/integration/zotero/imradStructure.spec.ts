/**
 * A minimal, valid PDF 1.4. ASCII only, so the string's length is its byte
 * length and the xref offsets are exact. With `bookmarks`, the catalog gets a
 * native `/Outlines` tree whose entries point at the top of their page.
 */
function makePdf(
  pagesSpec: readonly (readonly Line[])[],
  bookmarks: readonly { title: string; page: number }[] = [],
): Uint8Array {
  const objects: string[] = [];
  const add = (objectBody: string): number => {
    objects.push(objectBody);
    return objects.length;
  };
  const catalog = add("");
  const pages = add("");
  const regular = add("<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>");
  const bold = add(
    "<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica-Bold >>",
  );
  const kids: number[] = [];
  for (const lines of pagesSpec) {
    let y = 740;
    const ops = lines.map((line) => {
      y -= line.gapAbove;
      return `BT /${line.font} ${line.size} Tf 72 ${y} Td (${line.text}) Tj ET`;
    });
    const stream = ops.join("\n");
    const contents = add(
      `<< /Length ${stream.length} >>\nstream\n${stream}\nendstream`,
    );
    kids.push(
      add(
        `<< /Type /Page /Parent ${pages} 0 R /MediaBox [0 0 612 792] ` +
          `/Resources << /Font << /F1 ${regular} 0 R /F2 ${bold} 0 R >> >> ` +
          `/Contents ${contents} 0 R >>`,
      ),
    );
  }
  let outlinesRef = "";
  if (bookmarks.length > 0) {
    const root = add("");
    const first = objects.length + 1;
    bookmarks.forEach((mark, i) => {
      const self = first + i;
      const kid = kids[mark.page] ?? assert.fail(`no page ${mark.page}`);
      add(
        `<< /Title (${mark.title}) /Parent ${root} 0 R` +
          (i > 0 ? ` /Prev ${self - 1} 0 R` : "") +
          (i < bookmarks.length - 1 ? ` /Next ${self + 1} 0 R` : "") +
          ` /Dest [${kid} 0 R /XYZ 72 760 0] >>`,
      );
    });
    objects[root - 1] =
      `<< /Type /Outlines /First ${first} 0 R /Last ${first + bookmarks.length - 1} 0 R /Count ${bookmarks.length} >>`;
    outlinesRef = ` /Outlines ${root} 0 R /PageMode /UseOutlines`;
  }
  objects[catalog - 1] =
    `<< /Type /Catalog /Pages ${pages} 0 R${outlinesRef} >>`;
  objects[pages - 1] =
    `<< /Type /Pages /Kids [${kids.map((k) => `${k} 0 R`).join(" ")}] /Count ${kids.length} >>`;

  let out = "%PDF-1.4\n";
  const offsets: number[] = [];
  objects.forEach((objectBody, i) => {
    offsets.push(out.length);
    out += `${i + 1} 0 obj\n${objectBody}\nendobj\n`;
  });
  const xrefAt = out.length;
  out += `xref\n0 ${objects.length + 1}\n0000000000 65535 f \n`;
  for (const offset of offsets) {
    out += `${String(offset).padStart(10, "0")} 00000 n \n`;
  }
  out += `trailer\n<< /Size ${objects.length + 1} /Root ${catalog} 0 R >>\nstartxref\n${xrefAt}\n%%EOF\n`;
  return new TextEncoder().encode(out);
}

