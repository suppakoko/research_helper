const created: Zotero.Item[] = [];
const tempFiles: string[] = [];

async function importFixture(
  name: string,
  bytes: Uint8Array,
): Promise<{ parent: Zotero.Item; attachment: Zotero.Item }> {
  const parent = new Zotero.Item("journalArticle");
  parent.setField("title", `P3-T21 IMRaD fixture ${name} ${Date.now()}`);
  await parent.saveTx();
  created.push(parent);
  const path = PathUtils.join(
    Zotero.getTempDirectory().path,
    `rh-p3t21-${name}-${Date.now()}.pdf`,
  );
  await IOUtils.write(path, bytes);
  tempFiles.push(path);
  const attachment = await Zotero.Attachments.importFromFile({
    file: path,
    parentItemID: parent.id,
    contentType: "application/pdf",
  });
  return { parent, attachment };
}

function isRecord(value: unknown): value is Record<string, unknown> {
  return typeof value === "object" && value !== null;
}

function keysOf(value: unknown): string {
  return isRecord(value) ? Object.keys(value).sort().join(",") : typeof value;
}

function countBy(values: readonly unknown[], key: string): string {
  const counts: Record<string, number> = {};
  for (const value of values) {
    const k = isRecord(value) ? String(value[key] ?? "(absent)") : "(?)";
    counts[k] = (counts[k] ?? 0) + 1;
  }
  return JSON.stringify(counts);
}

function clip(value: unknown, chars: number): string {
  const text = JSON.stringify(value) ?? String(value);
  return text.length > chars ? `${text.slice(0, chars)}…` : text;
}

/**
 * Print the decoded document's shape: the keys at each level, the outline
 * in full, every block's type, flow class, page and text, and one text node.
 */
function describeShape(name: string, doc: unknown, ms: number): void {
  const record = isRecord(doc) ? doc : {};
  const catalog = isRecord(record.catalog) ? record.catalog : {};
  const content = Array.isArray(record.content) ? record.content : [];
  const pages = Array.isArray(catalog.pages) ? catalog.pages : [];
  debug(
    `${LOG} ${name}: decoded in ${ms} ms; doc keys {${keysOf(doc)}}; ` +
      `schemaVersion ${String(record.schemaVersion)}; metadata ${clip(record.metadata, 300)}`,
  );
  debug(
    `${LOG} ${name}: catalog keys {${keysOf(catalog)}}; pages ${pages.length}; ` +
      `page[0] ${clip(pages[0], 300)}`,
  );
  debug(`${LOG} ${name}: catalog.outline ${clip(catalog.outline, 2500)}`);
  debug(
    `${LOG} ${name}: content ${content.length} blocks; types ${countBy(content, "type")}; ` +
      `flowClass ${countBy(content, "flowClass")}`,
  );
  content.forEach((block, i) => {
    if (!isRecord(block)) return;
    const anchor = isRecord(block.anchor) ? block.anchor : {};
    const kids = Array.isArray(block.content) ? block.content : [];
    debug(
      `${LOG} ${name}:   [${i}] type=${String(block.type)} keys={${keysOf(block)}} ` +
        `flowClass=${String(block.flowClass)} pageRects=${clip(anchor.pageRects, 120)} ` +
        `children=${kids.length} childKeys={${keysOf(kids[0])}} ` +
        `text=${clip(kids.map((k) => (isRecord(k) && typeof k.text === "string" ? k.text : "<block>")).join("|"), 160)}`,
    );
  });
  const firstNode = (function find(nodes: readonly unknown[]): unknown {
    for (const node of nodes) {
      if (isRecord(node) && typeof node.text === "string") return node;
      if (isRecord(node) && Array.isArray(node.content)) {
        const hit = find(node.content);
        if (hit !== undefined) return hit;
      }
    }
    return undefined;
  })(content);
  debug(`${LOG} ${name}: first text node ${clip(firstNode, 400)}`);
}

